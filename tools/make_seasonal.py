NORMAL_T = [t for t in T if t[1] is None]


# ── 수요 모델 ─────────────────────────────────────────────────────────
def bump_factor(d: date):
    """해당 날짜의 (배수, 지배 국면)."""
    mult, phase, best = 1.0, "평시", 0.0
    for center, half, peak, ph in BUMPS:
        dd = (d - center).days
        w = math.exp(-(dd * dd) / (2 * half * half))
        add = (peak - 1.0) * w
        mult += add
        if add > best:
            best, phase = add, ph
    return mult, (phase if best > 0.25 else "평시")


def daily_count(d: date, rnd: random.Random):
    span = (END - START).days or 1
    base = BASE_START + (BASE_END - BASE_START) * ((d - START).days / span)
    mult, phase = bump_factor(d)
    n = base * DOW[d.weekday()] * mult
    # 연휴 당일은 주말 계수를 상쇄한다 (명절은 요일과 무관하게 사람이 움직인다)
    if CHUSEOK_HOLIDAY[0] <= d <= CHUSEOK_HOLIDAY[1] and d.weekday() >= 5:
        n /= DOW[d.weekday()]
    # 일반 공휴일: 당일 접수 감소 → 다음 영업일 적체 해소
    if d in PUBLIC_HOLIDAYS:
        n *= HOLIDAY_MULT
    elif d in CATCHUP_DAYS:
        n *= CATCHUP_MULT
    return max(1, int(round(n * rnd.uniform(0.88, 1.12)))), phase


def pick_hour(rnd: random.Random, busy: bool):
    if busy:                      # 명절기는 이른 아침·늦은 밤까지 퍼진다
        w = [0,0,0,0,0,1,4,8,11,12,11,10,8,9,10,10,9,8,7,6,5,4,2,1]
    else:
        w = [0,0,0,0,0,0,1,4,9,14,14,12,7,9,12,11,8,6,4,3,2,1,0,0]
    return rnd.choices(range(24), weights=w, k=1)[0]


def holiday_name(d: date):
    return "추석" if d < date(2026, 11, 1) else "설"


def build_row(rnd: random.Random, d: date, phase: str, seq: int):
    hol_share = PHASE_WINDOW.get(phase, 0.0)
    use_hol = phase != "평시" and rnd.random() < hol_share
    유형, _, 제목t, 질문t, 답변t = rnd.choice(HOLIDAY_T[phase] if use_hol else NORMAL_T)
    if 유형 == "기타":
        유형 = rnd.choice(["예약발권", "할인적용", "시설", "앱오류"])

    v = vals(rnd)
    v["명절"] = holiday_name(d)
    hour = pick_hour(rnd, phase != "평시")
    등록 = datetime(d.year, d.month, d.day, hour, rnd.randint(0, 59), rnd.randint(0, 59))
    접수 = 등록 + timedelta(minutes=rnd.randint(5, 540))
    기한 = 접수 + timedelta(days=rnd.choice([3, 5, 7, 14]))
    # 명절기에는 처리가 밀린다 → 기한초과 비율이 올라간다
    lag = rnd.randint(0, 6) if phase == "평시" else rnd.randint(1, 16)
    완료 = 접수 + timedelta(days=lag, hours=rnd.randint(0, 20))
    미완료 = rnd.random() < (0.10 if phase == "평시" else 0.20)
    if 완료.date() > END and not 미완료:
        미완료 = True

    부서 = ("역무팀" if 유형 in ("입석혼잡", "역사혼잡", "명절수하물")
            else "단체운송팀" if 유형 in ("단체귀성", "단체")
            else "여객사업본부" if 유형 in ("귀성표예매", "임시열차", "반환위약금")
            else rnd.choice(처리부서))

    return {
        "접수번호": f"{d.strftime('%Y%m')}-{seq:08d}",
        "민원유형": 유형,
        "유입경로": rnd.choices(유입경로, weights=[26, 30, 20, 12, 6, 6] if phase == "평시"
                              else [22, 34, 26, 10, 4, 4], k=1)[0],
        "등록일": 등록.strftime("%Y-%m-%d %H:%M:%S"),
        "접수일": 접수.strftime("%Y-%m-%d %H:%M:%S"),
        "처리기한": 기한.strftime("%Y-%m-%d"),
        "완료일": "" if 미완료 else 완료.strftime("%Y-%m-%d %H:%M:%S"),
        "고객요구유형": rnd.choice(고객요구유형),
        "제목": 제목t.format(**v),
        "질문": 질문t.format(**v),
        "답변": 답변t.format(**v),
        "상위완료유형": "" if 미완료 else rnd.choice(상위완료유형),
        "완료유형": "" if 미완료 else rnd.choice(
            ["보상지급", "규정안내", "시설개선", "교육실시", "단순안내", "환불처리"]),
        "처리부서": 부서,
        "처리자": v["직원"],
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="seasonal_raw.csv")
    ap.add_argument("--seed", type=int, default=20260925)
    ap.add_argument("--profile", action="store_true", help="일별 건수만 출력")
    args = ap.parse_args()

    rnd = random.Random(args.seed)
    rows, seq = [], 0
    d = START
    prof = []
    while d <= END:
        n, phase = daily_count(d, rnd)
        prof.append((d, n, phase))
        if not args.profile:
            for _ in range(n):
                seq += 1
                rows.append(build_row(rnd, d, phase, seq))
        d += timedelta(days=1)

    if args.profile:
        for d, n, ph in prof:
            bar = "█" * max(0, round(n / 6))
            print(f"{d} {d.strftime('%a')} {n:4d} {ph:<4} {bar}")
        print(f"\n합계 {sum(n for _, n, _ in prof):,}건 / {len(prof)}일")
        return

    rows.sort(key=lambda r: r["등록일"])
    for i, r in enumerate(rows, 1):
        r["접수번호"] = f"{r['등록일'][:4]}{r['등록일'][5:7]}-{i:08d}"
    with open(args.out, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    print(f"{args.out} — {len(rows):,}행 ({START} ~ {END})")


if __name__ == "__main__":
    main()
